const AIEngine = {
    // Генерация ответа подозреваемого на основе улик и роли
    generateResponse: async function(suspect, question, caseData) {
        const q = question.toLowerCase();
        
        // Симуляция контекстного ИИ-анализа (Ролевой движок)
        if (q.includes("где") || q.includes("алиби") || q.includes("был")) {
            return `Я находился подальше от этого места. Зачем мне врать? Проверьте записи или спросите свидетелей!`;
        }
        
        if (q.includes("улика") || q.includes("следы") || q.includes("кровь") || q.includes("вино")) {
            if (suspect.isGuilty) {
                return `Вы пытаетесь пришить мне то, к чему я не имею отношения! Какое ещё ${question}? Вы заходите слишком далеко, детектив.`;
            } else {
                return `Да, я видел это, но не придал значения. Это никак со мной не связано.`;
            }
        }

        if (q.includes("почему") || q.includes("мотив") || q.includes("зачем")) {
            return `У каждого из нас были терки с жертвой, но убивать? Это безумие. Ищите того, у кого был реальный доступ.`;
        }

        // Базовые отклики
        const neutralAnswers = [
            `Детектив, вы теряете время на пустые вопросы. Внимательнее изучите улики!`,
            `Я скажу всё только в присутствии адвоката, если вы продолжите этот давить на меня.`,
            `Мне нечего скрывать, но и отвечать на бессмысленные догадки я не буду.`
        ];
        
        return neutralAnswers[Math.floor(Math.random() * neutralAnswers.length)];
    }
};
