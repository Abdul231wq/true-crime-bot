const Game = {
  all: CASES,
  pack: null,
  case: null,
  suspects: [],
  locations: [],
  questions: [],
  confronts: [],
  hypotheses: [],
  timeline: [],
  softHint: "",
  hardHint: "",

  loadChapter(n) {
    const idx = Math.max(0, Math.min(this.all.length - 1, (n || 1) - 1));
    const pack = this.all[idx];
    this.pack = pack;
    this.case = pack.meta;
    this.suspects = pack.suspects;
    this.locations = pack.locations;
    this.questions = pack.questions;
    this.confronts = pack.confronts;
    this.hypotheses = pack.hypotheses;
    this.timeline = pack.timeline;
    this.softHint = pack.softHint;
    this.hardHint = pack.hardHint;
    return pack;
  },

  hasNext() {
    return GameData.state.chapter < this.all.length;
  },

  nextPack() {
    return this.all[GameData.state.chapter] || null;
  },

  getSuspect(id) {
    return this.suspects.find((s) => s.id === id) || this.suspects[0];
  },
  getLocation(id) {
    return this.locations.find((x) => x.id === id);
  },
  getQuestion(id) {
    return this.questions.find((x) => x.id === id);
  },
  getHypothesis(id) {
    return this.hypotheses.find((x) => x.id === id);
  },
  getConfront(suspectId, clueId) {
    return this.confronts.find((c) => c.suspectId === suspectId && c.clueId === clueId);
  }
};

